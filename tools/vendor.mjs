// Copies the exact runtime files from node_modules into vendor/, so the site is plain
// static files with no build step. Run after changing versions in package.json.
//
// three is pinned below 0.162.0 on purpose: mind-ar 1.2.5 imports `sRGBEncoding` from
// three, and that export was removed in three 0.162.0.
//
// Usage: node tools/vendor.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const nodeModules = join(root, 'node_modules');

const pkg = (name) => JSON.parse(readFileSync(join(nodeModules, name, 'package.json'), 'utf8'));

// Copies `entries` (paths relative to srcDir) plus every relative import they reach.
function copyGraph(srcDir, destDir, entries) {
  const queue = [...entries];
  const copied = new Set();
  while (queue.length) {
    const rel = queue.pop();
    if (copied.has(rel)) continue;
    copied.add(rel);
    mkdirSync(dirname(join(destDir, rel)), { recursive: true });
    copyFileSync(join(srcDir, rel), join(destDir, rel));
    const code = readFileSync(join(srcDir, rel), 'utf8');
    const pattern = /\b(?:from|import)\s*["'](\.{1,2}\/[^"']+)["']/g;
    for (const match of code.matchAll(pattern)) {
      queue.push(posix.normalize(posix.join(posix.dirname(rel), match[1])));
    }
  }
  return [...copied].sort();
}

const mindAr = pkg('mind-ar');
const three = pkg('three');

const mindArFiles = copyGraph(
  join(nodeModules, 'mind-ar', 'dist'),
  join(root, 'vendor', 'mind-ar'),
  ['mindar-image-three.prod.js', 'mindar-image.prod.js'],
);
for (const name of ['LICENSE', 'README.md']) {
  copyFileSync(join(nodeModules, 'mind-ar', name), join(root, 'vendor', 'mind-ar', name));
}

const threeFiles = [
  'build/three.module.js',
  'examples/jsm/renderers/CSS3DRenderer.js',
];
for (const rel of threeFiles) {
  const dest = join(root, 'vendor', 'three', rel.replace(/^examples\/jsm\//, 'addons/').replace(/^build\//, ''));
  mkdirSync(dirname(dest), { recursive: true });
  copyFileSync(join(nodeModules, 'three', rel), dest);
}
copyFileSync(join(nodeModules, 'three', 'LICENSE'), join(root, 'vendor', 'three', 'LICENSE'));

writeFileSync(
  join(root, 'vendor', 'VERSIONS.txt'),
  [`mind-ar ${mindAr.version} (MIT)`, `three ${three.version} (MIT)`, '', 'Generated by tools/vendor.mjs. Do not edit by hand.'].join('\n'),
);

console.log(`mind-ar ${mindAr.version}:`);
for (const rel of mindArFiles) console.log(`  vendor/mind-ar/${rel}`);
console.log(`three ${three.version}:`);
for (const rel of ['three.module.js', 'addons/renderers/CSS3DRenderer.js']) console.log(`  vendor/three/${rel}`);
